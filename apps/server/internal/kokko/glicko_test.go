func TestLegacySchemaUpgrade(t *testing.T) {
	app := core.NewBaseApp(core.BaseAppConfig{DataDir: t.TempDir()})
	if err := app.Bootstrap(); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { app.ClearBootstrap() })
	var legacy core.MigrationsList
	for _, migration := range core.AppMigrations.Items() {
		if migration.File == "1770000000_initial.go" {
			legacy.Add(migration)
		}
	}
	if len(legacy.Items()) != 1 {
		t.Fatal("legacy migration missing")
	}
	if _, err := core.NewMigrationsRunner(app, legacy).Up(); err != nil {
		t.Fatal(err)
	}
	s := New(app)
	a, b := newUser(t, s, "First", "active"), newUser(t, s, "Second", "active")
	m := Match{ID: "legacy-match", Kind: "singles", Date: "2026-10-01", Order: 1, A: []string{a}, B: []string{b}, ScoreA: 21, ScoreB: 19, Author: a, Version: 3, Created: "original", Updated: "original"}
	if err := saveMatch(app, m); err != nil {
		t.Fatal(err)
	}
	for i, p := range []string{a, b} {
		before, after := 1000.0, 1016.0
		if i == 1 {
			after = 984
		}
		if err := exec(app, "INSERT INTO kokko_ratings VALUES({:p},'singles',{:a},1)", dbx.Params{"p": p, "a": after}); err != nil {
			t.Fatal(err)
		}
		if err := exec(app, "INSERT INTO kokko_rating_history VALUES('legacy-match',{:p},'singles',{:b},{:a},{:d},0.5)", dbx.Params{"p": p, "b": before, "a": after, "d": after - before}); err != nil {
			t.Fatal(err)
		}
	}
	preview, err := s.PreviewRatings()
	if err != nil || preview.Changed != 2 {
		t.Fatal(preview, err)
	}
	// Preview works against the actual old schema and cannot add the RD columns.
	var count struct{ Count int }
	if err = app.DB().NewQuery("SELECT count(*) AS count FROM pragma_table_info('kokko_ratings') WHERE name='rd'").One(&count); err != nil || count.Count != 0 {
		t.Fatal("preview migrated schema", err)
	}
	if err = app.RunAllMigrations(); err != nil {
		t.Fatal(err)
	}
	if err = s.EnsureRatings(); err != nil {
		t.Fatal(err)
	}
	assertReplay(t, s)
	if after, e := s.PreviewRatings(); e != nil || after.Changed != 0 || after.MatchDigest != preview.MatchDigest {
		t.Fatal(after, e)
	}
	ms, err := loadMatches(app)
	if err != nil || !reflect.DeepEqual(ms, []Match{m}) {
		t.Fatal("legacy source changed", err)
	}
}

