func TestGlickoGoldenVectors(t *testing.T) {
	data, err := os.ReadFile("testdata/glicko-vectors.json")
	if err != nil {
		t.Fatal(err)
	}
	var cases []struct {
		Name                     string
		A, B                     []Skill
		ExpectedA                float64
		WinA, LossA, WinB, LossB []Skill
	}
	if err = json.Unmarshal(data, &cases); err != nil {
		t.Fatal(err)
	}
	for _, c := range cases {
		t.Run(c.Name, func(t *testing.T) {
			if math.Abs(TeamWinProbability(c.A, c.B)-c.ExpectedA) > 1e-12 {
				t.Fatal("probability")
			}
			for side, own := range [][]Skill{c.A, c.B} {
				opp, win, loss := c.B, c.WinA, c.LossA
				if side == 1 {
					opp, win, loss = c.A, c.WinB, c.LossB
				}
				for i := range own {
					for score, want := range []Skill{loss[i], win[i]} {
						got, _ := UpdateTeamPlayer(own, opp, i, float64(score))
						if math.Abs(got.Rating-want.Rating) > 1e-9 || math.Abs(got.RD-want.RD) > 1e-9 {
							t.Fatalf("%+v != %+v", got, want)
						}
					}
				}
			}
		})
	}
}

func TestGlickoReplayOrderPoolsAndMargins(t *testing.T) {
	ms := []Match{
		{ID: "second", Kind: "doubles", Date: "2026-10-10", Order: 2, A: []string{"a", "c"}, B: []string{"b", "d"}, ScoreA: 21, ScoreB: 19},
		{ID: "first", Kind: "doubles", Date: "2026-10-10", Order: 1, A: []string{"a", "b"}, B: []string{"c", "d"}, ScoreA: 21, ScoreB: 0},
		{ID: "later", Kind: "doubles", Date: "2026-11-10", Order: 1, A: []string{"b", "a"}, B: []string{"d", "c"}, ScoreA: 28, ScoreB: 30},
	}
	before := encode(ms)
	want, ranks := Replay(ms, "doubles")
	if encode(ms) != before {
		t.Fatal("replay changed input ordering")
	}
	reversed := slices.Clone(ms)
	slices.Reverse(reversed)
	got, reversedRanks := Replay(reversed, "doubles")
	if !reflect.DeepEqual(want, got) || !reflect.DeepEqual(ranks, reversedRanks) {
		t.Fatal("input order affected replay")
	}
	for i := range reversed {
		if reversed[i].ScoreA > reversed[i].ScoreB {
			reversed[i].ScoreA, reversed[i].ScoreB = 30, 29
		} else {
			reversed[i].ScoreA, reversed[i].ScoreB = 0, 21
		}
	}
	reversed = append(reversed, Match{ID: "singles", Kind: "singles", Date: "2026-10-01", A: []string{"a"}, B: []string{"b"}, ScoreA: 21, ScoreB: 5}, Match{ID: "deleted", Kind: "doubles", Deleted: true, Date: "2026-10-01", A: []string{"a", "b"}, B: []string{"c", "d"}, ScoreA: 21, ScoreB: 0})
	got, _ = Replay(reversed, "doubles")
	if !reflect.DeepEqual(want, got) {
		t.Fatal("other discipline, deleted game or score margin affected ratings")
	}
	if want[8].BeforeRD <= want[4].AfterRD {
		t.Fatal("playing date gap did not age RD")
	}
}

func TestConfidenceAndInactivity(t *testing.T) {
	established, uncertain := Skill{1000, 50}, Skill{1000, 350}
	settled, _ := UpdateTeamPlayer([]Skill{established}, []Skill{established}, 0, 1)
	newcomer, _ := UpdateTeamPlayer([]Skill{uncertain}, []Skill{established}, 0, 1)
	unknownOpponent, _ := UpdateTeamPlayer([]Skill{established}, []Skill{uncertain}, 0, 1)
	if newcomer.Rating <= settled.Rating || unknownOpponent.Rating >= settled.Rating {
		t.Fatal("confidence not reflected")
	}
	if AgedRD(50, "2025-01-01", "2026-01-01") != 350 || AgedRD(50, "2026-01-01", "2026-01-01") != 50 {
		t.Fatal("daily variance")
	}
	s, ids := setup(t)
	mustMatch(t, s, ids[0], create(ids))
	before, err := s.State(ids[0], Filters{})
	if err != nil {
		t.Fatal(err)
	}
	s.Now = func() time.Time { return time.Date(2027, 1, 1, 0, 0, 0, 0, time.UTC) }
	after, err := s.State(ids[0], Filters{})
	if err != nil {
		t.Fatal(err)
	}
	for i, r := range before.Rankings {
		if after.Rankings[i].Rating != r.Rating || after.Rankings[i].RD <= r.RD {
			t.Fatal("idle state")
		}
	}
	if !reflect.DeepEqual(before.Ratings, after.Ratings) || before.Revision != after.Revision {
		t.Fatal("aging wrote history")
	}
}

func TestRatingMigrationAtomicAndIdempotent(t *testing.T) {
	s, ids := setup(t)
	mustMatch(t, s, ids[0], create(ids))
	q := create(ids)
	q.Kind = "singles"
	q.A = ids[:1]
	q.B = ids[1:2]
	mustMatch(t, s, ids[0], q)
	// Emulate legacy cached values after the additive schema migration.
	for _, query := range []string{"UPDATE kokko_ratings SET rating=1000,rd=350,last_played=''", "UPDATE kokko_rating_history SET after=1000,delta=0,before_rd=350,after_rd=350", "UPDATE kokko_meta SET rating_system=0"} {
		if err := exec(s.App, query, nil); err != nil {
			t.Fatal(err)
		}
	}
	preview, err := s.PreviewRatings()
	if err != nil {
		t.Fatal(err)
	}
	if preview.Matches != 2 || preview.History != 6 || preview.Changed != 6 {
		t.Fatal(preview)
	}
	ms, _ := loadMatches(s.App)
	// Fail during the second pool to prove neither pool nor the flag commits.
	if err = exec(s.App, "CREATE TRIGGER fail_replay BEFORE INSERT ON kokko_ratings WHEN NEW.kind='doubles' BEGIN SELECT RAISE(ABORT,'test'); END", nil); err != nil {
		t.Fatal(err)
	}
	if s.EnsureRatings() == nil {
		t.Fatal("expected migration failure")
	}
	var meta struct{ System, Revision int }
	if err = s.App.DB().NewQuery("SELECT rating_system AS system,revision FROM kokko_meta").One(&meta); err != nil {
		t.Fatal(err)
	}
	if meta.System != 0 {
		t.Fatal("partially migrated")
	}
	if again, e := s.PreviewRatings(); e != nil || again != preview {
		t.Fatal("failed replay changed cache", again, e)
	}
	if err = exec(s.App, "DROP TRIGGER fail_replay", nil); err != nil {
		t.Fatal(err)
	}
	if err = s.EnsureRatings(); err != nil {
		t.Fatal(err)
	}
	assertReplay(t, s)
	if after, e := s.PreviewRatings(); e != nil || after.Changed != 0 || after.MatchDigest != preview.MatchDigest {
		t.Fatal(after, e)
	}
	if err = s.EnsureRatings(); err != nil {
		t.Fatal(err)
	}
	var afterMeta struct{ System, Revision int }
	if err = s.App.DB().NewQuery("SELECT rating_system AS system,revision FROM kokko_meta").One(&afterMeta); err != nil {
		t.Fatal(err)
	}
	if afterMeta.System != RatingSystem || afterMeta.Revision != meta.Revision+1 {
		t.Fatal("not idempotent", afterMeta)
	}
	afterMatches, _ := loadMatches(s.App)
	if !reflect.DeepEqual(ms, afterMatches) {
		t.Fatal("match source changed")
	}
	// The migration must not reinterpret a future algorithm version.
	if err = exec(s.App, "UPDATE kokko_meta SET rating_system={:s}", dbx.Params{"s": RatingSystem + 1}); err != nil {
		t.Fatal(err)
	}
	if s.EnsureRatings() == nil {
		t.Fatal("accepted future system")
	}
}
